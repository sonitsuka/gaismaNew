import PageBackground from "@/components/ui/pageBackground"
import MasonryGallery, { type GalleryPhoto } from "@/components/masonry-gallery"
import photos from "@/public/photos/modeling.json"
import type { Metadata } from "next"

// What the photos without a "section" of their own are filed under. They are
// the bulk of the page, so they come last; named sections lead.
const REST = "Editorial & Campaign"

export const metadata: Metadata = {
  title: "Modeling — Runway, Editorial and Campaign",
  description:
    "Runway, editorial and campaign modelling work by Alisa Scetinina.",
  alternates: { canonical: "/modeling" },
  openGraph: { title: "Modeling — Runway, Editorial and Campaign | GAISMA", description: "Runway, editorial and campaign modelling work by Alisa Scetinina.", url: "/modeling" },
}

export default function ModelingPage() {
  // Order matters: the gallery deals photos across the columns in turn, so this
  // sequence reads left-to-right across the top. Generated by
  // scripts/optimize-photos.mjs into public/photos — edit modeling.json to
  // reorder or reword, not the filenames.
  //
  // A photo with a "section" in modeling.json is grouped under that heading, in
  // the order the sections first appear in the file.
  const all = photos as GalleryPhoto[]
  const blocks = all.reduce<{ name: string; photos: GalleryPhoto[] }[]>((acc, p) => {
    const name = p.section ?? REST
    const found = acc.find((b) => b.name === name)
    if (found) found.photos.push(p)
    else acc.push({ name, photos: [p] })
    return acc
  }, [])
  blocks.sort((a, b) => Number(a.name === REST) - Number(b.name === REST))

  return (
    <div className="text-white min-h-screen">
      <PageBackground page="modeling" />
      <div className="relative w-full h-32 sm:h-48 md:h-64 overflow-hidden">
        <div className="absolute inset-0 flex items-center z-30">
          <div className="container mx-auto px-4 md:px-8">
            <h1 className="text-3xl sm:text-5xl md:text-6xl font-bold text-white">
              <span className="text-white">Modeling</span>
            </h1>
            <p className="mt-3 max-w-xl text-sm sm:text-base text-white/70">
              Editorial, runway and campaign work.
            </p>
          </div>
        </div>
      </div>

      <div className="container mx-auto px-4 sm:px-6 md:px-8 py-6 md:py-12 space-y-12 md:space-y-16">
        {blocks.map((block) => (
          <section key={block.name} id={block.name.toLowerCase().replace(/[^a-z0-9]+/g, "-")}>
            <h2 className="text-xl sm:text-2xl md:text-3xl font-semibold mb-6 text-white relative inline-block">
              <span className="text-white">{block.name}</span>
              <span className="absolute -bottom-2 left-0 w-full h-px bg-gradient-to-r from-white/50 to-transparent"></span>
            </h2>
            <MasonryGallery photos={block.photos} />
          </section>
        ))}
      </div>
    </div>
  )
}
